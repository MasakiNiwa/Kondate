import { NUTRIENT_KEYS, type Food, type FoodCategory, type Nutrients } from './types';

/**
 * 食材のデータ。
 * 栄養素は「日本食品標準成分表（八訂）」をもとに丸めた 100g あたりの概算値。
 * 値段・パックの大きさ・日持ちは、一般的なスーパーの目安。
 *
 * 栄養素の並び: エネルギー kcal, たんぱく質 g, 脂質 g, 炭水化物 g, 食物繊維 g, 食塩相当量 g,
 *   カルシウム mg, 鉄 mg, ビタミンA µgRAE, ビタミンD µg, ビタミンB1 mg, ビタミンB2 mg, ビタミンC mg, カリウム mg
 */
type N = [
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
];

function nut(v: N): Nutrients {
  return Object.fromEntries(NUTRIENT_KEYS.map((k, i) => [k, v[i]])) as Nutrients;
}

/** 買う食材: [g, 単位, 円, 日持ち] */
function f(
  id: string,
  name: string,
  category: FoodCategory,
  pack: [number, string, number, number],
  peakMonths: number[],
  v: N,
  extra: Partial<Food> = {},
): Food {
  const [packGrams, packLabel, price, shelfDays] = pack;
  return {
    id,
    name,
    category,
    per100: nut(v),
    pantry: false,
    packGrams,
    packLabel,
    price,
    shelfDays,
    freezable: category === 'meat' || category === 'fish',
    peakMonths,
    ...extra,
  };
}

/** 常備品（調味料・乾物・米など） */
function p(id: string, name: string, category: FoodCategory, v: N): Food {
  return {
    id,
    name,
    category,
    per100: nut(v),
    pantry: true,
    packGrams: 0,
    packLabel: '',
    price: 0,
    shelfDays: 365,
    freezable: false,
    peakMonths: [],
  };
}

