import type { Cuisine, Dish, DishRole, Protein, Thermal } from './types';

/**
 * 料理のデータ（夕食向け・手軽に作れて美味しいもの）。
 * 材料は「食材 ID:1 人分の g」をカンマでつなぐ（水・だし汁は含めない）。
 */
function d(
  id: string,
  name: string,
  role: DishRole,
  minutes: number,
  thermal: Thermal,
  cuisine: Cuisine,
  protein: Protein,
  ingredients: string,
  howto: string,
  opts: Partial<Dish> = {},
): Dish {
  return {
    id,
    name,
    role,
    minutes,
    thermal,
    cuisine,
    protein,
    ingredients: ingredients.split(',').map((s) => {
      const [foodId, g] = s.trim().split(':');
      return { foodId, grams: Number(g) };
    }),
    howto,
    ...opts,
  };
}

